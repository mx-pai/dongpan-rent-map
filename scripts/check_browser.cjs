 await page.locator('#detail [data-action="copy-route"]').last().click()
 assert.equal((await page.evaluate(()=>navigator.clipboard.readText())).match(/https:\/\/uri.amap.com\/navigation/g).length,3)
 await page.locator('#fullscreen').click();assert.equal(await page.locator('#fullscreen').getAttribute('aria-pressed'),'true');assert.equal(Math.round((await page.locator('.explorer').boundingBox()).height),1000);await page.keyboard.press('Escape')
 assert.equal(await page.locator('#fullscreen').getAttribute('aria-pressed'),'false')
 await page.goto(url);await page.waitForFunction(()=>window.rentMapReady)
